-- Independent comparison evidence. Existing training records remain unchanged.
CREATE TABLE IF NOT EXISTS tddt4iots_research.ai_comparison_case (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    researcher_id BIGINT NOT NULL,
    experiment_code VARCHAR(100) NOT NULL,
    phase VARCHAR(16) NOT NULL CHECK (phase IN ('PILOT', 'EVALUATION')),
    system_code VARCHAR(100) NOT NULL,
    requirements_version VARCHAR(40) NOT NULL,
    input_sha256 CHAR(64) NOT NULL,
    effective_input TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (researcher_id, experiment_code, phase, system_code, requirements_version)
);

CREATE TABLE IF NOT EXISTS tddt4iots_research.ai_comparison_run (
    id UUID PRIMARY KEY,
    case_id BIGINT NOT NULL REFERENCES tddt4iots_research.ai_comparison_case(id),
    researcher_id BIGINT NOT NULL,
    project_id VARCHAR(512) NOT NULL,
    model_registration_id BIGINT NOT NULL,
    model_owner_id BIGINT NOT NULL,
    requested_model VARCHAR(200) NOT NULL,
    returned_model VARCHAR(200),
    repetition INTEGER NOT NULL CHECK (repetition > 0),
    attempt INTEGER NOT NULL CHECK (attempt > 0),
    prompt_version VARCHAR(40) NOT NULL,
    schema_version VARCHAR(40) NOT NULL,
    source_commit VARCHAR(200) NOT NULL,
    request_evidence JSONB NOT NULL,
    source_documents JSONB NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'STARTED'
        CHECK (status IN ('STARTED','SERVER_VALIDATED','FAILED','REFUSED')),
    provider_response TEXT,
    raw_output TEXT,
    parsed_workspace JSONB,
    usage JSONB,
    latency_ms BIGINT CHECK (latency_ms >= 0),
    error_message TEXT,
    client_status VARCHAR(24) CHECK (client_status IN ('IMPORTED','VALIDATION_FAILED','IMPORT_FAILED','CAPTURE_FAILED','DECLINED')),
    client_report JSONB,
    original_imported_workspace JSONB,
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMPTZ,
    client_reported_at TIMESTAMPTZ,
    UNIQUE (case_id, model_registration_id, repetition, attempt)
);
CREATE INDEX IF NOT EXISTS ix_comparison_run_project
    ON tddt4iots_research.ai_comparison_run(researcher_id, project_id, started_at);
COMMENT ON COLUMN tddt4iots_research.ai_comparison_run.original_imported_workspace IS
    'One-time client snapshot immediately after import, before human edits. Not an expert quality assessment.';
