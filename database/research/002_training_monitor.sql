-- Operational fine-tuning monitor for PostgreSQL.
-- Run after the existing application schema and 001_ai_experiment_studio.sql.

ALTER TABLE training_history ADD COLUMN IF NOT EXISTS provider_job_id VARCHAR(200);
ALTER TABLE training_history ADD COLUMN IF NOT EXISTS provider_status VARCHAR(40);
ALTER TABLE training_history ADD COLUMN IF NOT EXISTS progress_percent DOUBLE PRECISION;
ALTER TABLE training_history ADD COLUMN IF NOT EXISTS last_monitored_at TIMESTAMP;
ALTER TABLE training_history ADD COLUMN IF NOT EXISTS monitoring_failures INTEGER NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS training_monitor_snapshot (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    training_history_id BIGINT NOT NULL REFERENCES training_history(id) ON DELETE CASCADE,
    provider_job_id     VARCHAR(200) NOT NULL,
    provider_status     VARCHAR(40) NOT NULL,
    progress_percent    DOUBLE PRECISION CHECK (progress_percent IS NULL OR progress_percent BETWEEN 0 AND 100),
    checked_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    duration_ms         BIGINT CHECK (duration_ms IS NULL OR duration_ms >= 0),
    response_payload    TEXT,
    error_message       TEXT
);

CREATE TABLE IF NOT EXISTS training_monitor_event (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    training_history_id BIGINT NOT NULL REFERENCES training_history(id) ON DELETE CASCADE,
    provider_event_id   VARCHAR(200) NOT NULL UNIQUE,
    level               VARCHAR(30),
    message             TEXT,
    provider_created_at BIGINT,
    data_payload        TEXT,
    captured_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS training_monitor_checkpoint (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    training_history_id     BIGINT NOT NULL REFERENCES training_history(id) ON DELETE CASCADE,
    provider_checkpoint_id  VARCHAR(200) NOT NULL UNIQUE,
    fine_tuned_model        VARCHAR(250),
    step_number             BIGINT,
    provider_created_at     BIGINT,
    metrics_payload         TEXT,
    captured_at             TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_training_monitor_snapshot_history
    ON training_monitor_snapshot(training_history_id, checked_at DESC);
CREATE INDEX IF NOT EXISTS ix_training_monitor_event_history
    ON training_monitor_event(training_history_id, provider_created_at DESC);
CREATE INDEX IF NOT EXISTS ix_training_monitor_checkpoint_history
    ON training_monitor_checkpoint(training_history_id, step_number);
CREATE INDEX IF NOT EXISTS ix_training_history_monitorable
    ON training_history(provider_status, last_monitored_at)
    WHERE result_trining IS NOT NULL;

COMMENT ON TABLE training_monitor_snapshot IS 'Every automatic provider polling response, including failed monitor calls.';
COMMENT ON TABLE training_monitor_event IS 'Deduplicated fine-tuning events returned by the provider.';
COMMENT ON TABLE training_monitor_checkpoint IS 'Deduplicated fine-tuning checkpoints and their metric payloads.';
