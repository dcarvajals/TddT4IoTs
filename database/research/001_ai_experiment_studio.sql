-- TDDT4IoTs AI Experiment Studio - PostgreSQL 15+
-- Additive schema: it does not modify or delete current training_history records.

CREATE SCHEMA IF NOT EXISTS tddt4iots_research;

CREATE TABLE IF NOT EXISTS tddt4iots_research.ai_dataset_version (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(160) NOT NULL,
    version             VARCHAR(40) NOT NULL,
    description         TEXT,
    schema_version      VARCHAR(40) NOT NULL,
    manifest_sha256     CHAR(64) NOT NULL,
    source_commit       VARCHAR(200),
    status              VARCHAR(24) NOT NULL DEFAULT 'DRAFT'
                        CHECK (status IN ('DRAFT','REVIEW','FROZEN','ARCHIVED')),
    total_items         INTEGER NOT NULL DEFAULT 0 CHECK (total_items >= 0),
    train_items         INTEGER NOT NULL DEFAULT 0 CHECK (train_items >= 0),
    validation_items    INTEGER NOT NULL DEFAULT 0 CHECK (validation_items >= 0),
    test_items          INTEGER NOT NULL DEFAULT 0 CHECK (test_items >= 0),
    created_by_person_id BIGINT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    frozen_at           TIMESTAMPTZ,
    UNIQUE (name, version),
    UNIQUE (manifest_sha256)
);

CREATE TABLE IF NOT EXISTS tddt4iots_research.ai_dataset_item (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_version_id  BIGINT NOT NULL REFERENCES tddt4iots_research.ai_dataset_version(id) ON DELETE CASCADE,
    external_project_id VARCHAR(160),
    project_hash        CHAR(64) NOT NULL,
    split               VARCHAR(16) NOT NULL CHECK (split IN ('TRAIN','VALIDATION','TEST')),
    domain              VARCHAR(100),
    language            VARCHAR(12) NOT NULL DEFAULT 'es',
    source_type         VARCHAR(24) CHECK (source_type IN ('TEXT','TXT','PDF','DOC','DOCX','MIXED','SYNTHETIC')),
    complexity          VARCHAR(16) CHECK (complexity IN ('LOW','MEDIUM','HIGH')),
    input_requirements  JSONB NOT NULL,
    gold_workspace      JSONB NOT NULL,
    traceability_gold   JSONB,
    input_tokens        INTEGER CHECK (input_tokens IS NULL OR input_tokens >= 0),
    gold_tokens         INTEGER CHECK (gold_tokens IS NULL OR gold_tokens >= 0),
    pii_removed         BOOLEAN NOT NULL DEFAULT FALSE,
    review_status       VARCHAR(24) NOT NULL DEFAULT 'PENDING'
                        CHECK (review_status IN ('PENDING','IN_REVIEW','APPROVED','REJECTED')),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    approved_at         TIMESTAMPTZ,
    UNIQUE (dataset_version_id, project_hash)
);

CREATE TABLE IF NOT EXISTS tddt4iots_research.ai_human_review (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_item_id     BIGINT NOT NULL REFERENCES tddt4iots_research.ai_dataset_item(id) ON DELETE CASCADE,
    reviewer_person_id  BIGINT,
    review_round        SMALLINT NOT NULL DEFAULT 1 CHECK (review_round > 0),
    correctness         SMALLINT CHECK (correctness BETWEEN 1 AND 5),
    completeness        SMALLINT CHECK (completeness BETWEEN 1 AND 5),
    consistency         SMALLINT CHECK (consistency BETWEEN 1 AND 5),
    readability         SMALLINT CHECK (readability BETWEEN 1 AND 5),
    usability           SMALLINT CHECK (usability BETWEEN 1 AND 5),
    correction_seconds  INTEGER CHECK (correction_seconds IS NULL OR correction_seconds >= 0),
    added_elements      INTEGER NOT NULL DEFAULT 0 CHECK (added_elements >= 0),
    changed_elements    INTEGER NOT NULL DEFAULT 0 CHECK (changed_elements >= 0),
    deleted_elements    INTEGER NOT NULL DEFAULT 0 CHECK (deleted_elements >= 0),
    decision            VARCHAR(16) NOT NULL CHECK (decision IN ('APPROVE','REVISE','REJECT')),
    notes               TEXT,
    reviewed_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (dataset_item_id, reviewer_person_id, review_round)
);

CREATE TABLE IF NOT EXISTS tddt4iots_research.ai_experiment (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                VARCHAR(80) NOT NULL UNIQUE,
    name                VARCHAR(200) NOT NULL,
    research_question   TEXT,
    hypothesis          TEXT,
    method              VARCHAR(40) NOT NULL
                        CHECK (method IN ('CURRENT_BASELINE','PROMPT','FEW_SHOT','MULTI_STAGE','FINE_TUNING','DISTILLATION','ABLATION')),
    dataset_version_id  BIGINT NOT NULL REFERENCES tddt4iots_research.ai_dataset_version(id),
    base_model          VARCHAR(160) NOT NULL,
    model_snapshot      VARCHAR(200),
    prompt_version      VARCHAR(40) NOT NULL,
    schema_version      VARCHAR(40) NOT NULL,
    source_commit       VARCHAR(200) NOT NULL,
    parameters          JSONB NOT NULL DEFAULT '{}'::jsonb,
    fixed_seed          BIGINT,
    repetitions         SMALLINT NOT NULL DEFAULT 1 CHECK (repetitions > 0),
    status              VARCHAR(20) NOT NULL DEFAULT 'PLANNED'
                        CHECK (status IN ('PLANNED','RUNNING','COMPLETED','FAILED','CANCELLED')),
    created_by_person_id BIGINT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at          TIMESTAMPTZ,
    completed_at        TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS tddt4iots_research.ai_training_run (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id       BIGINT NOT NULL REFERENCES tddt4iots_research.ai_experiment(id) ON DELETE CASCADE,
    provider_job_id     VARCHAR(200),
    provider            VARCHAR(60) NOT NULL,
    base_model          VARCHAR(160) NOT NULL,
    resulting_model     VARCHAR(200),
    training_file_id    VARCHAR(200),
    validation_file_id  VARCHAR(200),
    status              VARCHAR(24) NOT NULL,
    epochs              INTEGER,
    batch_size          INTEGER,
    learning_rate_multiplier NUMERIC(12,6),
    seed                BIGINT,
    trained_tokens      BIGINT,
    training_loss       DOUBLE PRECISION,
    validation_loss     DOUBLE PRECISION,
    validation_token_accuracy DOUBLE PRECISION,
    estimated_cost_usd  NUMERIC(14,6),
    actual_cost_usd     NUMERIC(14,6),
    raw_provider_result JSONB,
    error_message       TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at          TIMESTAMPTZ,
    finished_at         TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS tddt4iots_research.ai_training_checkpoint (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    training_run_id     BIGINT NOT NULL REFERENCES tddt4iots_research.ai_training_run(id) ON DELETE CASCADE,
    provider_checkpoint_id VARCHAR(200),
    step_number         INTEGER NOT NULL CHECK (step_number >= 0),
    epoch_number        NUMERIC(10,4),
    training_loss       DOUBLE PRECISION,
    validation_loss     DOUBLE PRECISION,
    training_token_accuracy DOUBLE PRECISION,
    validation_token_accuracy DOUBLE PRECISION,
    recorded_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (training_run_id, step_number)
);

CREATE TABLE IF NOT EXISTS tddt4iots_research.ai_inference_run (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id       BIGINT NOT NULL REFERENCES tddt4iots_research.ai_experiment(id) ON DELETE CASCADE,
    dataset_item_id     BIGINT NOT NULL REFERENCES tddt4iots_research.ai_dataset_item(id),
    repetition          SMALLINT NOT NULL DEFAULT 1 CHECK (repetition > 0),
    model_snapshot      VARCHAR(200) NOT NULL,
    prompt_version      VARCHAR(40) NOT NULL,
    schema_version      VARCHAR(40) NOT NULL,
    seed                BIGINT,
    raw_output          TEXT,
    parsed_workspace    JSONB,
    validation_errors   JSONB NOT NULL DEFAULT '[]'::jsonb,
    validation_warnings JSONB NOT NULL DEFAULT '[]'::jsonb,
    success             BOOLEAN NOT NULL DEFAULT FALSE,
    refused             BOOLEAN NOT NULL DEFAULT FALSE,
    repair_count        INTEGER NOT NULL DEFAULT 0 CHECK (repair_count >= 0),
    retry_count         INTEGER NOT NULL DEFAULT 0 CHECK (retry_count >= 0),
    prompt_tokens       INTEGER CHECK (prompt_tokens IS NULL OR prompt_tokens >= 0),
    completion_tokens   INTEGER CHECK (completion_tokens IS NULL OR completion_tokens >= 0),
    latency_ms          BIGINT CHECK (latency_ms IS NULL OR latency_ms >= 0),
    cost_usd            NUMERIC(14,6),
    error_message       TEXT,
    executed_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (experiment_id, dataset_item_id, repetition)
);

CREATE TABLE IF NOT EXISTS tddt4iots_research.ai_metric_result (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inference_run_id    BIGINT NOT NULL REFERENCES tddt4iots_research.ai_inference_run(id) ON DELETE CASCADE,
    metric_group        VARCHAR(40) NOT NULL,
    metric_name         VARCHAR(100) NOT NULL,
    metric_value        DOUBLE PRECISION NOT NULL,
    numerator           DOUBLE PRECISION,
    denominator         DOUBLE PRECISION,
    details             JSONB NOT NULL DEFAULT '{}'::jsonb,
    evaluator_version   VARCHAR(60) NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (inference_run_id, metric_name, evaluator_version)
);

CREATE TABLE IF NOT EXISTS tddt4iots_research.ai_artifact (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id       BIGINT REFERENCES tddt4iots_research.ai_experiment(id) ON DELETE CASCADE,
    inference_run_id    BIGINT REFERENCES tddt4iots_research.ai_inference_run(id) ON DELETE CASCADE,
    artifact_type       VARCHAR(30) NOT NULL
                        CHECK (artifact_type IN ('DATASET_MANIFEST','PROMPT','JSON_SCHEMA','RAW_RESPONSE','WORKSPACE','CSV','REPORT','FIGURE')),
    storage_path        TEXT NOT NULL,
    sha256              CHAR(64) NOT NULL,
    mime_type           VARCHAR(120),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (experiment_id IS NOT NULL OR inference_run_id IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS ix_ai_dataset_item_split ON tddt4iots_research.ai_dataset_item(dataset_version_id, split);
CREATE INDEX IF NOT EXISTS ix_ai_dataset_item_domain ON tddt4iots_research.ai_dataset_item(domain, complexity);
CREATE INDEX IF NOT EXISTS ix_ai_experiment_dataset ON tddt4iots_research.ai_experiment(dataset_version_id, status);
CREATE INDEX IF NOT EXISTS ix_ai_inference_experiment ON tddt4iots_research.ai_inference_run(experiment_id, success);
CREATE INDEX IF NOT EXISTS ix_ai_metric_name ON tddt4iots_research.ai_metric_result(metric_name, metric_value);

CREATE OR REPLACE VIEW tddt4iots_research.v_experiment_summary AS
SELECT e.id,
       e.code,
       e.name,
       e.method,
       e.base_model,
       e.status,
       COUNT(r.id) AS total_runs,
       COUNT(r.id) FILTER (WHERE r.success) AS successful_runs,
       ROUND(100.0 * COUNT(r.id) FILTER (WHERE r.success) / NULLIF(COUNT(r.id), 0), 2) AS success_rate_pct,
       ROUND(AVG(r.latency_ms), 2) AS mean_latency_ms,
       PERCENTILE_CONT(0.5) WITHIN GROUP (ORDER BY r.latency_ms) AS p50_latency_ms,
       PERCENTILE_CONT(0.95) WITHIN GROUP (ORDER BY r.latency_ms) AS p95_latency_ms,
       SUM(r.prompt_tokens) AS prompt_tokens,
       SUM(r.completion_tokens) AS completion_tokens,
       SUM(r.cost_usd) AS total_cost_usd
FROM tddt4iots_research.ai_experiment e
LEFT JOIN tddt4iots_research.ai_inference_run r ON r.experiment_id = e.id
GROUP BY e.id, e.code, e.name, e.method, e.base_model, e.status;

CREATE OR REPLACE VIEW tddt4iots_research.v_metric_summary AS
SELECT r.experiment_id,
       m.metric_group,
       m.metric_name,
       COUNT(*) AS sample_size,
       AVG(m.metric_value) AS mean_value,
       STDDEV_SAMP(m.metric_value) AS standard_deviation,
       PERCENTILE_CONT(0.5) WITHIN GROUP (ORDER BY m.metric_value) AS median_value,
       PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY m.metric_value) AS q1,
       PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY m.metric_value) AS q3
FROM tddt4iots_research.ai_metric_result m
JOIN tddt4iots_research.ai_inference_run r ON r.id = m.inference_run_id
GROUP BY r.experiment_id, m.metric_group, m.metric_name;

COMMENT ON SCHEMA tddt4iots_research IS 'Reproducible datasets, training runs, inference runs and scientific metrics for TDDT4IoTs.';
